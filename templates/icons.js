// Add icons to B namespace
if (typeof window !== 'undefined' && window.B) {
  window.B.icons = icons;
  
  /**
   * Create icon element
   * @param {string} name - Icon name
   * @param {string} className - Additional classes
   * @returns {HTMLElement}
   */
  window.B.icon = function(name, className = '') {
    const iconSvg = icons[name];
    if (!iconSvg) {
      console.warn(`B-Labs: Icon "${name}" not found`);
      return document.createElement('span');
    }
    
    const span = document.createElement('span');
    span.className = `b-icon ${className}`.trim();
    span.innerHTML = iconSvg;
    return span;
  };
  
  /**
   * Initialize icon elements
   * Converts <i data-icon="name"> to actual SVG icons
   */
  window.B.initIcons = function() {
    const iconElements = document.querySelectorAll('[data-icon]');
    iconElements.forEach(el => {
      const iconName = el.getAttribute('data-icon');
      const iconSvg = icons[iconName];
      if (iconSvg) {
        const existingClasses = el.className;
        el.className = `b-icon ${existingClasses}`.trim();
        el.innerHTML = iconSvg;
      }
    });
  };
  
  // Auto-init on load
  window.B.ready(() => {
    window.B.initIcons();
  });
}

